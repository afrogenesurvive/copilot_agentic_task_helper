// ── Notification centre: record + broadcast ──────────────────────────────────
/**
 * Record one notification and push it to every window.
 *
 * The single funnel for producers: applies NOTIFY_ENABLED, keeps this store the
 * only writer of the feed, and leaves presentation to the renderer (a dot, a row)
 * — main holds no view state.
 */
function notify(n) {
  if (!NOTIFY_ENABLED) return null;
  const entry = notifications.record(n);
  if (!entry) return null;
  for (const w of BrowserWindow.getAllWindows()) {
    try {
      w.webContents.send("notifications:new", entry);
    } catch {
      /* window gone */
    }
  }
  // The menu-bar badge counts these, so it is repainted from the same funnel —
  // no polling, and it updates while the panel is closed.
  void updateTrayBadge();
  return entry;
}

const clip = (text, n = 200) => {
  const s = String(text ?? "")
    .replace(/\s+/g, " ")
    .trim();
  return s.length > n ? `${s.slice(0, n)}…` : s;
};

/**
 * Derive notifications from the live log stream.
 *
 * Every component writes `logs/live/*.jsonl` and the tail started at app-ready
 * already feeds the Logs view, so the webhook server and the agent runner need no
 * new IPC — which is why the producers could stay entirely inside this process.
 * The agent runner's `frontdesk_reply` failures arrive the same way (the runner
 * logs them to `logs/live` through mcp/agent-runner/logger.js).
 *
 * The startup cutoff is load-bearing: `seedFromLive()` replays up to 3 days of
 * history, and without it the first launch after this ships would raise hundreds
 * of notifications from that backlog.
 */
function startNotificationProducers() {
  const startedAt = new Date().toISOString();
  // Throttle for crypto failures. `/api/license/verify` is a PUBLIC route, so without
  // this a scripted bad-licence loop would turn into a notification flood. One
  // notification per (event, reason, seat) per minute is enough to notice.
  const cryptoNotifyAt = new Map();
  const CRYPTO_NOTIFY_MS = 60_000;

  liveLog.subscribe((entry) => {
    if (!entry || !entry.ts || entry.ts < startedAt) return;
    const data = entry.data || {};

    // A new frontdesk item on the priority queue — the v2 licence path and the
    // legacy Trello mirror both land here (event-queue.js logs sub + text).
    if (entry.source === "webhook" && entry.subSource === "queue" && data.queue === "priority" && data.source === "frontdesk") {
      notify({
        source: "queue",
        title: "New frontdesk message",
        body: clip([data.sub, data.text].filter(Boolean).join(" · ")) || `Queued as #${data.seqNo ?? "?"}`,
        data: { eventId: data.id, seqNo: data.seqNo, sub: data.sub },
      });
      return;
    }

    // A seat signed in. Logouts are deliberately not news.
    if (entry.source === "frontdesk" && entry.subSource === "session" && data.action === "login") {
      notify({
        source: "sessions",
        title: `${data.user || "A seat"} signed in`,
        body: clip([data.ip, data.timezone].filter(Boolean).join(" · ")),
        data: { user: data.user, ip: data.ip },
      });
      return;
    }

    // Frontdesk crypto. Two things the operator must not have to go looking for:
    // a sign-in or session that was rejected, and a reply that could not be encrypted
    // (no registered seat key) — the latter means someone is waiting for an answer that
    // will never arrive. The generic error branch below would catch the `error`-level
    // ones; these are emitted at `warn` too, so they need their own branch.
    if (entry.source === "frontdesk" && entry.subSource === "crypto" && data.ok === false) {
      const key = `${data.event}|${data.reason}|${data.sub || ""}`;
      const last = cryptoNotifyAt.get(key) || 0;
      if (Date.now() - last >= CRYPTO_NOTIFY_MS) {
        cryptoNotifyAt.set(key, Date.now());
        const isReply = data.event === "outbound_encrypt";
        notify({
          source: isReply ? "chat" : "security",
          level: entry.level === "error" ? "error" : "warn",
          title: isReply ? "Frontdesk reply not delivered" : `Frontdesk ${String(data.event || "").replace(/_/g, " ")} failed`,
          body: clip([data.sub, data.reason].filter(Boolean).join(" · ")),
          data: { ts: entry.ts, event: data.event, reason: data.reason, sub: data.sub },
        });
      }
      return;
    }

    // Errors from any process. A failed frontdesk reply is chat news (someone is
    // waiting for an answer); everything else is a log-level problem.
    if (entry.level === "error") {
      const isFrontdeskReply = entry.source === "runner" && String(data.eventType || "").startsWith("frontdesk/");
      notify({
        source: isFrontdeskReply ? "chat" : "logs",
        level: "error",
        title: isFrontdeskReply
          ? "Frontdesk reply failed"
          : `${entry.source}${entry.subSource ? `/${entry.subSource}` : ""} error`,
        body: clip(entry.message),
        data: { ts: entry.ts },
      });
    }
  });
}

